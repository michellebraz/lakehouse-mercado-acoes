DROP TABLE IF EXISTS dbo.posicoes;
DROP TABLE IF EXISTS dbo.clientes;
DROP TABLE IF EXISTS dbo.ativos;
DROP TABLE IF EXISTS dbo.controle_watermark;

CREATE TABLE dbo.ativos (
  ticker VARCHAR(12) NOT NULL PRIMARY KEY,
  empresa NVARCHAR(100) NOT NULL,
  setor NVARCHAR(60) NOT NULL,
  tipo VARCHAR(10) NOT NULL,
  updated_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME());

CREATE TABLE dbo.clientes (
  cliente_id INT NOT NULL PRIMARY KEY,
  nome NVARCHAR(100) NOT NULL,
  cidade NVARCHAR(60) NOT NULL,
  uf CHAR(2) NOT NULL,
  perfil_investidor NVARCHAR(20) NULL,
  data_cadastro DATE NOT NULL,
  updated_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME());

CREATE TABLE dbo.posicoes (
  cliente_id INT NOT NULL REFERENCES dbo.clientes(cliente_id),
  ticker VARCHAR(12) NOT NULL REFERENCES dbo.ativos(ticker),
  quantidade INT NOT NULL,
  preco_medio DECIMAL(18,2) NOT NULL,
  updated_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT pk_posicoes PRIMARY KEY (cliente_id, ticker));

CREATE INDEX ix_ativos_updated_at ON dbo.ativos(updated_at);
CREATE INDEX ix_clientes_updated_at ON dbo.clientes(updated_at);
CREATE INDEX ix_posicoes_updated_at ON dbo.posicoes(updated_at);

CREATE TABLE dbo.controle_watermark (
  tabela VARCHAR(100) NOT NULL PRIMARY KEY,
  ultimo_valor DATETIME2 NOT NULL);

